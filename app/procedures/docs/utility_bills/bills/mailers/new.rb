class Docs::UtilityBills::Bills::Mailers::New < Notifier::Mailer

  class Docs::UtilityBills::Bills::Mailers::New::Autofetched < Docs::UtilityBills::Bills::Mailers::New

    consumes_event! 'bbps_bills.new_bill'

    assign :to do |user, params|
      bill = params[:record]
      bill.subscription.pocs.pluck(:email)
    end

    assign :subject do |user, params|
      subscription = params[:record]&.subscription
      "New Utility Bill Available for #{subscription.name} - #{subscription.sequence_id}"
    end

    assign :title do |user, params|
      subscription = params[:record]&.subscription
      "New Utility Bill Available"
    end

    assign :sub_header do |user, params|
      subscription = params[:record]&.subscription
      "A New Utility Bill is Available for #{subscription.name} - #{subscription.sequence_id}"
    end

    assign :hero_bg_image, "bg_document_approved.png"

    assign :tables do |user, params|
      bill = params[:record]
      tables = []

      tables.push(Docs::UtilityBills::Bills::Mailers::TableBuilder.(bill))
    end
  end

  class Docs::UtilityBills::Bills::Mailers::New::Manual < Docs::UtilityBills::Bills::Mailers::New

    consumes_event! 'bbps_bills.new_bill'

    assign :to do |user, params|
      bill = params[:record]
      bill.subscription.pocs.pluck(:email)
    end

    assign :subject do |user, params|
      subscription = params[:record]&.subscription
      "Bill generated by Finly for #{subscription.name} - #{subscription.sequence_id}"
    end

    assign :title do |user, params|
      subscription = params[:record]&.subscription
      "Utility Bill Generated"
    end

    assign :sub_header do |user, params|
      subscription = params[:record]&.subscription
      "A New Utility Bill is Generated for #{subscription.name} - #{subscription.sequence_id}"
    end

    assign :tables do |user, params|
      tables = []

      tables.push(Docs::UtilityBills::Bills::Mailers::TableBuilder.(params[:record]))
    end
  end
end