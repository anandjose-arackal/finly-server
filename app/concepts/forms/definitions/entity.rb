module Forms
  module Definitions

    class EntityContract
      def self.build(&block)
        Class.new(Dry::Validation::Contract) do
          params do
            required(:section).filled
            required(:field_key).filled
            required(:label).filled
            required(:placeholder).filled
            optional(:hint)
            required(:field_type).filled
            optional(:default_value)
            required(:editable).value(:bool?)
            required(:required).value(:bool?)
            optional(:active).filled(:bool?)
            optional(:unique).filled(:bool?)
            optional(:visible).filled(:bool?)
            optional(:multiple).filled(:bool?)
            optional(:position).filled(:int?)
            optional(:custom_field).filled(:bool?)
            optional(:dependent).filled(:bool?)
            optional(:conditional_required).filled(:bool?)
            optional(:can_visible_be_changed).filled(:bool?)
            optional(:can_editable_be_changed).filled(:bool?)
            optional(:can_required_be_changed).filled(:bool?)
            optional(:can_uniqueness_be_changed).filled(:bool?)
            optional(:can_be_disabled).filled(:bool?)
            optional(:can_label_be_renamed).filled(:bool?)
            optional(:can_not_be_hidden).filled(:bool?)
            optional(:can_be_filtered).filled(:bool?)
            optional(:can_choices_be_changed).filled(:bool?)
            optional(:show_in_bulk_import).filled(:bool?)
            optional(:allow_sort_in_filter).filled(:bool?)
            optional(:allow_clearing_default_value).filled(:bool?)

            optional(:choices).array do
              hash do
                optional(:id)
                required(:value).filled
                required(:position).value(:int?)
                required(:active).value(:bool?)
              end
            end
            required(:options) do
              hash do
                instance_exec &block if block_given?
              end
            end
          end
        end
      end
    end

    class Entity
      extend Dry::Monads[:result]
      include Registry
      include Schema
      include ::Forms::Definitions::Contract::DSL
      include Filter

      attr_accessor :options

      class_attribute :registered_type

      attribute :section
      attribute :field_key
      attribute :label, default: ->(*args) { self.field_key&.to_s&.humanize }
      attribute :placeholder, default: "Enter value"
      attribute :hint
      attribute :field_type, default: ->(*args) { self.registered_type }
      attribute :default_value
      attribute :editable, default: true
      attribute :required, default: false
      attribute :active, default: true
      attribute :unique, default: false
      attribute :visible, default: true
      attribute :position
      attribute :custom_field, default: false
      attribute :chained
      attribute :dependent, default: false
      attribute :conditional_required, default: false
      attribute :multiple, default: false

      # option :char_limit #, default: 1000
      # option :min_items
      # option :max_items
      # option :multiple # Pair with dropdown to make it multi-select dropdown
      # option :regex #, default: {format: "", message: "is invalid"}
      # option :choices #, default: []
      # option :enum #, default: { provider: nil, chained: [], filters: {} }

      attribute :can_visible_be_changed, default: false
      attribute :can_editable_be_changed, default: false
      attribute :can_required_be_changed, default: false
      attribute :can_uniqueness_be_changed, default: false
      attribute :can_be_disabled, default: false
      attribute :can_label_be_renamed, default: true
      attribute :can_not_be_hidden, default: true
      attribute :can_be_filtered, default: true
      attribute :can_choices_be_changed, default: true
      attribute :show_in_bulk_import, default: false
      attribute :allow_sort_in_filter, default: false
      attribute :allow_clearing_default_value, default: true
      # attribute :link, "/" # Generated by provider

      # Todo map_field support
      # class_attr :map_field_id

      def initialize(section, field_key, opts = {}, &block)
        self.section = section
        field_key(field_key)
        section(section)
        self.options = opts
        initialize_with(opts)

        instance_eval &block if block_given?
      end

      def initialize_with(opts)
        opts.each_pair do |key, value|
          next if value.nil?
          send :"#{ key }=", value
        end
      end

      def inspect
        "#<Entity##{self.registered_type}:#{object_id} @schema=#{schema.as_json}>"
      end

    end
  end
end


