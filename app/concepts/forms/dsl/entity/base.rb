module Forms
  module DSL
    module Entity
      class Base
        extend Dry::Monads[:result]
        include Registry
        include Schema
        include Forms::DSL::Entity::Contract::DSL
        include Forms::Generators::Filters::DSL

        attr_accessor :options

        class_attribute :registered_type

        attribute :form
        attribute :section
        attribute :field_key
        attribute :field_path, default: ->(*args) { self.field_key&.to_s }
        attribute :label, default: ->(*args) { self.field_key&.to_s&.humanize }
        attribute :placeholder, default: "Enter value"
        attribute :hint
        attribute :field_type, default: ->(*args) { self.registered_type }
        attribute :default_value
        attribute :editable, default: true
        attribute :required, default: false
        attribute :active, default: true
        attribute :unique, default: false
        attribute :visible, default: true
        attribute :position
        attribute :custom_field, default: false
        attribute :chained
        attribute :dependent, default: false
        attribute :conditional_required, default: false
        attribute :multiple, default: false
        attribute :scope
        attribute :internal, default: false
        attribute :is_modified, default: false
        attribute :populate_if_empty

        # option :char_limit #, default: 1000
        # option :min_items
        # option :max_items
        # option :multiple # Pair with dropdown to make it multi-select dropdown
        # option :regex #, default: {format: "", message: "is invalid"}
        # option :choices #, default: []
        # option :enum #, default: { provider: nil, chained: [], filters: {} }

        attribute :can_visible_be_changed, default: false
        attribute :can_editable_be_changed, default: false
        attribute :can_required_be_changed, default: false
        attribute :can_uniqueness_be_changed, default: false
        attribute :can_be_disabled, default: false
        attribute :can_label_be_renamed, default: true
        attribute :can_not_be_hidden, default: true
        attribute :can_be_filtered, default: true
        attribute :can_choices_be_changed, default: true
        attribute :show_in_bulk_import, default: false
        attribute :allow_sort_in_filter, default: false
        attribute :allow_clearing_default_value, default: true
        attribute :associate_custom_fields, default: false
        # attribute :link, "/" # Generated by provider

        # Todo map_field support
        # class_attr :map_field_id

        def initialize(section, field_key, parent_path, opts = {}, &block)
          self.section = section
          field_key(field_key)
          full_path = parent_path.present? ? "#{parent_path}/#{field_key}" : "#{field_key}"
          field_path(full_path)
          section(section)
          self.options = opts || {}
          initialize_with(opts)

          instance_eval &block if block_given?
        end

        def initialize_with(opts)
          opts.each_pair do |key, value|
            next if value.nil?
            send :"#{ key }=", value
          end
        end

        def inspect
          "#<Entity##{self.registered_type}:#{object_id} @schema=#{schema.as_json}>"
        end

        # Todo - Deprecated since we are generating the forms from database.
        # Todo - This was old implementation of generating forms directly from class
        # def builder_args
        #   [field_key, schema, {}, contract_block, collection: false]
        # end
        #
        # def build
        #   transformer = Forms::Contracts::EntityBuilder.new(*builder_args)
        #   transformer.generate
        # end

        def contract_block
          return nil unless entities.present?

          entities = self.entities

          lambda do |*args|
            entities.each do |entity|
              instance_eval &entity.build
            end
          end
        end
      end
    end
  end
end


